#!/usr/bin/env node
// Generates src/generated/openapi.ts from ./openapi.json with openapi-typescript.
//
// The CDA spec reuses one operationId for GET and HEAD /api/v1/health, which makes
// openapi-typescript emit a duplicate `operations` member. We de-duplicate operationIds
// in memory (suffixing the HTTP method) before generating; the spec file is untouched.
//
// To refresh the spec: curl -s https://cryptodataapi.com/api/openapi.json -o openapi.json
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "../openapi.json");
const outPath = resolve(here, "../src/generated/openapi.ts");

const spec = JSON.parse(readFileSync(specPath, "utf8"));
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];
const seen = new Set();
let renamed = 0;
for (const item of Object.values(spec.paths ?? {})) {
  for (const method of METHODS) {
    const op = item?.[method];
    if (!op?.operationId) continue;
    if (seen.has(op.operationId)) {
      op.operationId = `${op.operationId}__${method}`;
      renamed++;
    }
    seen.add(op.operationId);
  }
}

const ast = await openapiTS(spec);
const header = `// AUTO-GENERATED by packages/cda-client/scripts/gen.mjs from openapi.json (spec ${spec.info?.version ?? "unknown"}).\n// Do not edit by hand; run \`pnpm gen\` at the repo root.\n\n`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + astToString(ast));
console.log(`gen: wrote ${outPath} (${Object.keys(spec.paths ?? {}).length} paths, ${renamed} duplicate operationIds renamed)`);
